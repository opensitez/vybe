use super::helpers::compile_ok;

#[test]
fn test_linkage_section_syntax() {
    compile_ok(
        r#"
IDENTIFICATION DIVISION.
PROGRAM-ID. SUBPROG.
DATA DIVISION.
LINKAGE SECTION.
01 LNK-ELEMENTARY PIC X(5).
01 LNK-GROUP.
   05 LNK-SUB1 PIC 9(3).
   05 LNK-SUB2 PIC X(3).
01 LNK-TABLE.
   05 LNK-ENTRY OCCURS 5 TIMES PIC 9(2).
PROCEDURE DIVISION USING LNK-ELEMENTARY LNK-GROUP LNK-TABLE.
    DISPLAY LNK-ELEMENTARY.
    DISPLAY LNK-SUB1.
    DISPLAY LNK-ENTRY(1).
    GOBACK.
"#,
    );
}

#[test]
fn test_linkage_redefines_and_88() {
    compile_ok(
        r#"
IDENTIFICATION DIVISION.
PROGRAM-ID. SUBPROG.
DATA DIVISION.
LINKAGE SECTION.
01 LNK-STATUS PIC X.
   88 IS-OK VALUE "Y".
01 LNK-STATUS-RED REDEFINES LNK-STATUS PIC 9.
PROCEDURE DIVISION USING LNK-STATUS.
    IF IS-OK
        DISPLAY "OK"
    END-IF.
    GOBACK.
"#,
    );
}

