use crate::helpers;

macro_rules! cobol_test {
    ($name:ident, $src:expr, $expected:expr) => {
        #[test]
        fn $name() {
            let out = crate::helpers::run_prints($src);
            assert_eq!(out, $expected);
        }
    };
}

cobol_test!(
    test_cond_single_true,
    "IDENTIFICATION DIVISION. PROGRAM-ID. T. DATA DIVISION. WORKING-STORAGE SECTION. 01 X PIC 9 VALUE 1. 88 IS-ONE VALUE 1. PROCEDURE DIVISION. IF IS-ONE DISPLAY 'Y' END-IF. STOP RUN.",
    vec!["Y"]
);
