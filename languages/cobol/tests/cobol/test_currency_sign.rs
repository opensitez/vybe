#[test]
fn currency_sign_runtime_basic_output() {
    let out = run_prints(
        "IDENTIFICATION DIVISION.\nPROGRAM-ID. CUR11.\nENVIRONMENT DIVISION.\nCONFIGURATION SECTION.\nSPECIAL-NAMES.\n    CURRENCY SIGN IS \"$\".\nDATA DIVISION.\nWORKING-STORAGE SECTION.\n01 AMT PIC $9.99 VALUE $12.34.\nPROCEDURE DIVISION.\n    IF AMT > 0\n        DISPLAY \"HAS_SIGN\"\n    END-IF\n    STOP RUN.",
    );
    assert_eq!(out, vec!["HAS_SIGN"]);
}

