#[test]
fn input_output_section_with_io_control_currently_rejected() {
    let src = r#"
IDENTIFICATION DIVISION.
PROGRAM-ID. T.
ENVIRONMENT DIVISION.
INPUT-OUTPUT SECTION.
FILE-CONTROL.
    SELECT F ASSIGN TO "f.dat"
        ORGANIZATION IS SEQUENTIAL.
I-O-CONTROL.
DATA DIVISION.
FILE SECTION.
FD F.
01 R PIC X(20).
PROCEDURE DIVISION.
    OPEN OUTPUT F.
    MOVE "A" TO R.
    WRITE R.
    CLOSE F.
    STOP RUN.
"#;
    assert!(!parse_ok(src));
}

