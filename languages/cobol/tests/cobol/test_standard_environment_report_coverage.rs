use super::helpers::parse_ok;

#[test]
fn configuration_section_source_and_object_computer_parse() {
    let src = r#"
IDENTIFICATION DIVISION.
PROGRAM-ID. T.
ENVIRONMENT DIVISION.
CONFIGURATION SECTION.
SOURCE-COMPUTER. IBM-Z.
OBJECT-COMPUTER. IBM-Z.
DATA DIVISION.
WORKING-STORAGE SECTION.
01 X PIC 9 VALUE 1.
PROCEDURE DIVISION.
    DISPLAY X.
    STOP RUN.
"#;
    assert!(parse_ok(src));
}

