#[test]
fn test_linkage_section_with_call_and_return() {
    compile_ok(
        r#"
IDENTIFICATION DIVISION.
PROGRAM-ID. OUTER.
WORKING-STORAGE SECTION.
01 WS-VALUE PIC X(4) VALUE "ABCD".
PROCEDURE DIVISION.
    CALL "INNER" USING WS-VALUE.
    STOP RUN.

IDENTIFICATION DIVISION.
PROGRAM-ID. INNER.
DATA DIVISION.
LINKAGE SECTION.
01 LNK-VALUE PIC X(4).
PROCEDURE DIVISION USING LNK-VALUE.
    DISPLAY LNK-VALUE.
    GOBACK.
END PROGRAM INNER.

END PROGRAM OUTER.
"#,
    );
}

