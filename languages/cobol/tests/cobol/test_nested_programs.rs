use super::helpers::compile_ok;

#[test]
fn test_nested_program_structure() {
    compile_ok(
        r#"
IDENTIFICATION DIVISION.
PROGRAM-ID. OUTERPROG.
DATA DIVISION.
WORKING-STORAGE SECTION.
01 WS-A PIC X(5) VALUE "OUTER".
PROCEDURE DIVISION.
    DISPLAY WS-A.
    CALL "INNERPROG".
    STOP RUN.

IDENTIFICATION DIVISION.
PROGRAM-ID. INNERPROG.
DATA DIVISION.
WORKING-STORAGE SECTION.
01 WS-B PIC X(5) VALUE "INNER".
PROCEDURE DIVISION.
    DISPLAY WS-B.
    GOBACK.
END PROGRAM INNERPROG.

END PROGRAM OUTERPROG.
"#,
    );
}

