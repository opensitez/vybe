fn compile_ok(src: &str) {
    let module = vybe_language_js::parse(src).expect("parse failed");
    let profile =
        vybe_compiler::profile::parse_profile(vybe_language_js::profile_source())
            .expect("Failed to parse JS profile");
    let res = vybe_compiler::compiler::Compiler::with_profile(profile).compile(&module);
    assert!(res.is_ok(), "compile failed: {:?}", res.err());
}

